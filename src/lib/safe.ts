import type { Listing } from "./types";

/** Strip reporter identities from public listing payloads. */
export function publicListing(l: Listing) {
  const { reports, ...rest } = l;
  return { ...rest, reportCount: new Set(reports.map((r) => r.userId)).size };
}

export function sniffImage(buf: Buffer): "jpg" | "png" | "webp" | null {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpg";
  if (buf.length >= 8 && buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) return "png";
  if (buf.length >= 12 && buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") return "webp";
  return null;
}
